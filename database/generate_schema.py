def username_for(name: str) -> str:
    parts = name.replace("Dr. ", "").split()
    return f"{parts[0].lower()}.{parts[-1].lower().replace('al-', '')}"


def main():
    security = DataSecurity()
    out = [HEADER]
    out.append("INSERT INTO Sensors (sensor_id, location, falaj_name) VALUES\n" +
               ",\n".join(f"({i}, 'Location {i}', '{f}')" for i, f in enumerate(FALAJ, 1)) + ";\n")
    out.append("INSERT INTO Gates (gate_id, location, falaj_name) VALUES\n" +
               ",\n".join(f"({i}, 'Gate {i}', '{f}')" for i, f in enumerate(FALAJ, 1)) + ";\n")
    farms = []
    for i, f in enumerate(FALAJ, 1):
        farms.append(f"({i * 10 + 1}, 'Farm {i}-1', '{f}', 5.0)")
        farms.append(f"({i * 10 + 2}, 'Farm {i}-2', '{f}', 7.5)")
    out.append("INSERT INTO Farms (farm_id, location, falaj_name, size) VALUES\n" + ",\n".join(farms) + ";\n")

    users, seen = [], set()
    rows = [(k + 1, n, "farmer", (k // 2 + 1) * 10 + (k % 2 + 1)) for k, n in enumerate(FARMERS)]
    rows += [(uid, n, r, "NULL") for uid, n, r in STAFF]
    for uid, name, role, farm in rows:
        username = username_for(name)
        assert username not in seen, username
        seen.add(username)
        users.append(f"({uid}, '{username}', '{security.hash_password(config.DEFAULT_PASSWORD)}', "
                     f"'{name}', '{role}', {config.ROLE_LEVELS[role]}, {farm})")
    out.append("INSERT INTO Users (user_id, username, password_hash, name, role, access_level, farm_id) "
               "VALUES\n" + ",\n".join(users) + ";\n")

    slots, sid = [], 1
    for f in FALAJ:
        for h in ("06:00", "12:00", "18:00"):
            slots.append(f"({sid}, '{h}', '{f}', NULL)")
            sid += 1
    out.append("INSERT INTO TimeSlots (slot_id, start_time, falaj_name, reserved_by) VALUES\n" +
               ",\n".join(slots) + ";\n")
    hist = [f"({a}, {s}, 'WATER_LEAK', '{t}', 'Resolved', '{FALAJ[s - 1]} - Location {s}')"
            for a, s, t in ALERTS]
    out.append("-- Historical leak alerts (already resolved)\n"
               "INSERT INTO Maintenance (maintenance_id, sensor_id, issue_type, reported_date, status, location) "
               "VALUES\n" + ",\n".join(hist) + ";\n")
    path = os.path.join(os.path.dirname(__file__), "schema.sql")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("Wrote", path)


if __name__ == "__main__":
    main()
